#!/usr/bin/env node
// Final step: make store-assets/ a clean, self-contained, movable folder.
// - copies only the frames/sprites the kit actually uses into source/frames/ and rewrites plan.json to point there
// - keeps the play scripts in source/scripts/ (so a later run can replay the game)
// - deletes work/ (raw captures, contact sheets, temp builds, job files)
// - writes README.md (what each file is and where it gets uploaded)
// Usage: node pack.mjs [--dir store-assets] [--keep-work]
import fs from 'node:fs';
import path from 'node:path';
import { args, outDir } from './lib.mjs';

const a = args();
const dir = path.resolve(a.dir || outDir());
const R = p => path.join(dir, p);
if (!fs.existsSync(R('brand.json'))) { console.error('No brand.json in ' + dir); process.exit(1); }
const planPath = R('plan.json');
const plan = fs.existsSync(planPath) ? JSON.parse(fs.readFileSync(planPath, 'utf8')) : {};

// 1) every work/ file referenced by plan.json -> source/frames/
const moved = {};
const keep = v => {
  if (typeof v === 'string' && v.startsWith('work/') && /\.(png|jpe?g|webp)$/i.test(v)) {
    if (!moved[v]) {
      const dst = 'source/frames/' + path.basename(v);
      fs.mkdirSync(R('source/frames'), { recursive: true });
      if (fs.existsSync(R(v))) fs.copyFileSync(R(v), R(dst));
      moved[v] = dst;
    }
    return moved[v];
  }
  if (Array.isArray(v)) return v.map(keep);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, keep(x)]));
  return v;
};
const newPlan = keep(plan);
fs.writeFileSync(planPath, JSON.stringify(newPlan, null, 2));

// 2) play scripts / move plans -> source/scripts/
if (fs.existsSync(R('work'))) {
  for (const f of fs.readdirSync(R('work'))) {
    if (/\.(mjs|js|txt)$/.test(f) && !f.startsWith('.')) {
      fs.mkdirSync(R('source/scripts'), { recursive: true });
      fs.copyFileSync(R('work/' + f), R('source/scripts/' + f));
    }
  }
}

// 3) drop scratch
for (const f of ['.brand.resolved.json', '.brand.tmp.json']) fs.rmSync(R(f), { force: true });
if (!a['keep-work']) fs.rmSync(R('work'), { recursive: true, force: true });

// 4) README
const brand = JSON.parse(fs.readFileSync(R('brand.json'), 'utf8'));
const ls = d => fs.existsSync(R(d)) ? fs.readdirSync(R(d)).filter(f => !f.startsWith('.')) : [];
const shots = ls('play-store/screenshots');
fs.writeFileSync(R('README.md'), `# ${brand.name} — store kit

Generated by game-store-kit. This folder is self-contained: move it anywhere. Open \`preview.html\` to see everything.

## Upload / use
| File | Where it goes |
|---|---|
| \`play-store/icon-512.png\` | Play Console → Main store listing → App icon |
| \`play-store/feature-graphic-1024x500.png\` | Play Console → Feature graphic |
| \`play-store/screenshots/\` (${shots.length}) | Play Console → Phone screenshots (upload in order) |
| \`android/res/*\` | Copy into your app's \`android/app/src/main/res/\` (launcher icons, adaptive layers, Android 12 splash icon) |
| \`ios/AppIcon-1024.png\` | Xcode → Assets → AppIcon (single size) / App Store Connect |
| \`splash/\` | Splash / launch images (portrait, landscape, 2732² universal) |
| \`icon/icon.svg\`, \`icon/fg.svg\`, \`icon/bg.svg\` | Editable icon sources; \`icon/concepts/\` = alternative icons |
| \`brand/\` | Logo and character art taken from the game |

## Rebuild (same look, new tweaks)
\`brand.json\` (colors, fonts, style) and \`plan.json\` (frames, captions) drive everything.
Edit them, then run:

\`\`\`bash
node ~/.claude/skills/game-store-kit/scripts/build.mjs --dir "<this folder>"
\`\`\`

\`source/frames/\` holds the gameplay frames used; \`source/scripts/\` holds the play script used to capture them.
`);
const size = d => { let t = 0; const w = p => { for (const e of fs.readdirSync(p, { withFileTypes: true })) { const f = path.join(p, e.name); e.isDirectory() ? w(f) : t += fs.statSync(f).size; } }; w(d); return t; };
console.log(`Packed ${dir}  (${(size(dir) / 1e6).toFixed(1)} MB, ${Object.keys(moved).length} frames kept${a['keep-work'] ? ', work/ kept' : ', work/ removed'})`);
